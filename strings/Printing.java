public class Printing {
    public static void main(String[] args) {
        float a = 431.21124567f;
        System.out.printf(" %.2f",a);
        //print floating digit till 2 digit after decimal

        System.out.printf("\n%.3f",a);
        //print floating digit till 3 digit after the decimal

        System.out.printf("\nHello my name is %s and i am %s " , "sanchita" , "Student");
        //%s is the placeholder , we can replace string in order here

    }
}
